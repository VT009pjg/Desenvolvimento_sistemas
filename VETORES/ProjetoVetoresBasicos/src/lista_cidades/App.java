package lista_cidades;

public class App {

	public static void main(String[] args) {
		String [] cidades = {"Valença", "Barra do Piraí", "Vassouras", "Volta Redonda", "Resende"};
		
		for(int i = 0; i < cidades.length; i++) {
			System.out.println("Posição " + i + ": " + cidades[i]);
		}

	}

}
